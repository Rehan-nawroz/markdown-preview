export function createSampleDocument(baseUrl: string): string {
  const imageSrc = `${baseUrl}sample-architecture.svg`;

  return [
    '# Welcome to Markform',
    '',
    'Markform is a single-document Markdown editor that runs entirely in your browser. Open a file, write, preview, and export — your document never leaves this device.',
    '',
    '> “The finest tool is one that disappears completely into the author’s workflow.”',
    '',
    '## Try the essentials',
    '',
    '- [x] Open or drop a Markdown file',
    '- [x] Write with the toolbar or keyboard shortcuts',
    '- [ ] Switch to Preview and export a clean HTML copy',
    '',
    '## A code block',
    '',
    '```js',
    'async function saveDocument(handle, contents) {',
    '  const writable = await handle.createWritable();',
    '  await writable.write(contents);',
    '  await writable.close();',
    '}',
    '```',
    '',
    '## A small table',
    '',
    '| Action | What happens |',
    '| --- | --- |',
    '| Open | Drop a file, choose one, or start blank |',
    '| Save | Writes back on Chrome and Edge; downloads elsewhere |',
    '| Preview | Rendered locally and sanitized before display |',
    '',
    '### A quote and a list',
    '',
    '> Markdown is a way to write for the web without fighting the web.',
    '',
    '1. Edit in the Edit tab.',
    '2. Check the result in Preview.',
    '3. Export clean HTML or print to PDF.',
    '',
    `![Markform’s local-first editing loop](${imageSrc})`,
    '',
    '*Figure 1: Your document moves from editor to sanitized preview without a server.*',
    '',
    'A footnote reference[^1].',
    '',
    '[^1]: Remote images referenced by a document are loaded from their hosts when previewed. The document itself is never uploaded.',
    '',
    '---',
    '',
    'Built for one file at a time.',
    '',
  ].join('\n');
}
